// Uses a fake browser microphone ONLY as a clearly labelled integration fixture.
// This does not certify real human clap detection or hardware timing.
import {createRequire} from 'node:module';
import {mkdirSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||undefined,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1280,height:900}});
await context.addInitScript(()=>{
  window.__micRequests=0;
  const original=navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
  navigator.mediaDevices.getUserMedia=(...args)=>{window.__micRequests++;return original(...args);};
});
const page=await context.newPage(),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(name,ok)=>{if(!ok)throw Error(name);checks.push(name);console.log('PASS '+name);};
const start=process.env.BASE_URL||'http://127.0.0.1:5173';
mkdirSync('test-results',{recursive:true});
try{
  await page.goto(start);
  await page.getByRole('button',{name:/欢快/}).click();
  await page.getByRole('textbox',{name:'宠物名字'}).waitFor();
  await page.getByRole('textbox',{name:'宠物名字'}).fill('波波');
  await page.getByRole('button',{name:'确认名字'}).click();
  await page.getByRole('button',{name:'开始探险 ↗'}).waitFor();
  check('首次孵化不申请麦克风；名字确认后保存',await page.evaluate(()=>JSON.parse(localStorage.getItem('bobo.pet')).name==='波波'&&window.__micRequests===0));
  await page.screenshot({path:'test-results/home-desktop.png'});
  await page.reload();await page.getByRole('button',{name:'开始探险 ↗'}).waitFor();
  check('刷新直接进入宠物首页',await page.getByRole('button',{name:'确认名字'}).count()===0);
  await page.getByRole('button',{name:'开始探险 ↗'}).click();
  await page.getByRole('button',{name:'看看风车'}).click();
  await page.getByRole('button',{name:/开心/}).click();
  await page.getByRole('button',{name:'开始挑战'}).waitFor();
  check('开发模式显式标记规则编排',await page.getByText('开发模式 / 规则后备编排 · 仅前两小节').count()===1);
  const before=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  await page.getByRole('button',{name:'简单一点',exact:true}).click();
  await page.waitForFunction(()=>document.body.textContent.includes('难度 1 / 3'));
  const simpler=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  check('降低难度且生成新 planId',simpler.plan.difficulty===1&&before.plan.planId!==simpler.plan.planId);
  await page.getByRole('button',{name:'慢一点',exact:true}).click();
  await page.waitForFunction(()=>document.body.textContent.includes('试听速度 85%'));
  const slow=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  check('慢速预览不改变 BPM 或 planId',slow.plan.bpm===simpler.plan.bpm&&slow.plan.planId===simpler.plan.planId);
  await page.getByRole('button',{name:'听听看 ♪'}).click();
  await page.waitForTimeout(300);
  check('Web Audio 示范高亮',await page.locator('.beat.active').count()>0);
  await page.getByRole('button',{name:'停止试听'}).click();
  await page.screenshot({path:'test-results/adventure-desktop.png'});
  await page.evaluate(()=>{
    window.__originalMic=navigator.mediaDevices.getUserMedia;
    navigator.mediaDevices.getUserMedia=()=>Promise.reject(new DOMException('测试夹具：拒绝授权','NotAllowedError'));
  });
  await page.getByRole('button',{name:'开始挑战'}).click();
  await page.getByText('测试夹具：拒绝授权').waitFor();
  check('权限拒绝后仍可试听和挑战按钮',await page.getByRole('button',{name:'听听看 ♪'}).isEnabled());
  await page.evaluate(()=>navigator.mediaDevices.getUserMedia=window.__originalMic);
  await page.getByRole('button',{name:'开始挑战'}).click();
  await page.getByRole('button',{name:'停止本次录音'}).waitFor();
  await page.getByRole('button',{name:'停止本次录音'}).click();
  await page.getByRole('button',{name:'开始挑战'}).waitFor();
  check('取消倒计时返回预览并释放麦克风',!(await page.evaluate(()=>fetch('/api/state').then(r=>r.json()))).analysis);
  const outgoing=[];
  page.on('request',r=>{if(r.url().includes('/api/analysis'))outgoing.push(JSON.parse(r.postData()));});
  await page.getByRole('button',{name:'开始挑战'}).click();
  await page.getByRole('button',{name:'保留这次'}).waitFor({timeout:25000});
  const analysis=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  check('假设备集成测试：Worklet 采集后产生实际检测摘要',analysis.state==='FEEDBACK'&&typeof analysis.analysis.detectedCount==='number');
  check('拍手原始音频没有上传',outgoing.length===1&&Object.keys(outgoing[0]).join()==='analysis'&&!JSON.stringify(outgoing[0]).includes('base64'));
  await page.getByRole('button',{name:'保留这次'}).click();
  await page.getByRole('button',{name:'试听我的作品 ♪'}).waitFor();
  const work=await page.evaluate(async()=>{const m=await import('/src/store/storage.js');const w=await m.loadWork();return {blobSize:w.blob.size,type:w.blob.type,planId:w.plan.planId};});
  check('保留真实采集 WAV 到 IndexedDB',work.blobSize>1000&&work.type==='audio/wav'&&work.planId===analysis.plan.planId);
  await page.reload();
  await page.getByRole('button',{name:'开始探险 ↗'}).waitFor();
  await page.getByRole('button',{name:'开始探险 ↗'}).click();
  await page.getByRole('button',{name:'看看风车'}).click();
  await page.getByRole('button',{name:'试听我的作品 ♪'}).waitFor();
  check('刷新回首页，已保留作品可以恢复试听',true);
  await page.getByRole('button',{name:'再练一次',exact:true}).click();
  await page.getByRole('button',{name:'开始挑战'}).click();
  await page.getByRole('button',{name:'停止本次录音'}).click();
  await page.getByRole('button',{name:'试听已保留版本'}).waitFor();
  const retained=await page.evaluate(async()=>{const m=await import('/src/store/storage.js');const w=await m.loadWork();return w.recordingId;});
  check('取消重录不覆盖已确认录音',retained===analysis.analysis.recordingId);
  await page.getByRole('button',{name:'试听已保留版本'}).click();
  await page.getByRole('button',{name:'试听我的作品 ♪'}).click();
  await page.waitForTimeout(400);
  check('独立真实拍手轨和旋律轨音量可控制',await page.locator('#clap-volume').count()===1&&await page.locator('#backing-volume').count()===1);
  await page.locator('#clap-volume').fill('0');
  await page.getByRole('button',{name:'停止试听'}).click();
  await page.getByRole('button',{name:'← 宠物'}).click();
  await page.getByRole('button',{name:'开始探险 ↗'}).click();
  await page.getByRole('button',{name:'看看风车'}).click();
  await page.getByRole('button',{name:'试听我的作品 ♪'}).waitFor();
  check('返回首页后保留作品状态',true);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/work-mobile.png',fullPage:true});
  check('手机竖屏无横向溢出',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByRole('button',{name:'删除本地作品'}).click();
  await page.getByRole('button',{name:'开始挑战'}).waitFor();
  check('删除本地作品',await page.evaluate(async()=>{const m=await import('/src/store/storage.js');return !(await m.loadWork());}));
  check('浏览器无 JS 错误',errors.length===0);
  console.log(JSON.stringify({fixture:'Chromium fake microphone, NOT human recording',passed:checks.length,errors},null,2));
}finally{await browser.close();}
